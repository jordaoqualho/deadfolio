export type MessageKey = keyof typeof portuguese;
export const en = Object.fromEntries(
  Object.keys(portuguese).map((key) => [key, key]),
) as Record<MessageKey, string>;
export const pt: Record<MessageKey, string> = portuguese;
export const dictionaries = { en, pt };
export function translate(locale: Locale, key: string): string {
  return dictionaries[locale][key as MessageKey] ?? key;
}
export function localePath(locale: Locale, path: string) {
  if (
    !path.startsWith("/") ||
    path.startsWith("//") ||
    /^\/(admin|api|media)(\/|$)/.test(path)
  )
    return path;
  const clean = path.replace(/^\/pt(?=\/|$)/, "") || "/";
  return locale === "pt" ? `/pt${clean === "/" ? "" : clean}` : clean;
}
